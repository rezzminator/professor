func TestPathClassNamesEachExclusion(t *testing.T) {
	cases := map[string]string{
		"src/app.go":                      "",
		"cmd/main.py":                     "",
		"web/app.ts":                      "",
		"Makefile":                        "",
		"src/app_test.go":                 classTest,
		"pkg/test_tool.py":                classTest,
		"pkg/tool_test.py":                classTest,
		"web/a.test.js":                   classTest,
		"web/b.spec.ts":                   classTest,
		"internal/testdata/x.go":          classTest,
		"tests/e2e.go":                    classTest,
		"test/t.go":                       classTest,
		"web/__tests__/c.js":              classTest,
		"lib/fixtures/f.go":               classTest,
		"README.md":                       classDoc,
		"notes.txt":                       classDoc,
		"guide.rst":                       classDoc,
		"docs/guide.go":                   classDoc,
		"pfm/docs/x.go":                   classDoc,
		"templates/generated/agents/a.md": classGenerated,
		"pfm/harness-prompts/generated/claude.md": classGenerated,
		"api/x.pb.go":         classGenerated,
		"z_gen.go":            classGenerated,
		"web/q.gen.ts":        classGenerated,
		"go.sum":              classLock,
		"Cargo.lock":          classLock,
		"package-lock.json":   classLock,
		"pnpm-lock.yaml":      classLock,
		"yarn.lock":           classLock,
		"npm-shrinkwrap.json": classLock,
	}
	for path, want := range cases {
		if got := pathClass(path, nil); got != want {
			t.Errorf("pathClass(%q) = %q, want %q", path, got, want)
		}
	}
	marked := []byte("// Code generated by stringer; DO NOT EDIT.\n\npackage x\n")
	if got := pathClass("src/kind_string.go", marked); got != classGenerated {
		t.Errorf("a file marked generated in its first lines = %q, want generated", got)
	}
	late := []byte("package x\n\n\n\n\n// Code generated by stringer; DO NOT EDIT.\n")
	if got := pathClass("src/kind_string.go", firstLines(late)); got != "" {
		t.Errorf("a mark past the first 5 lines = %q, want counted", got)
	}
}

// testRepo writes files under a fresh repository and returns its directory.
func testRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	runGit(t, dir, "init", "-q")
	return dir
}

func runGit(t *testing.T, dir string, args ...string) string {
	t.Helper()
	full := append([]string{
		"-C", dir, "-c", "user.name=test", "-c", "user.email=test@example.invalid",
		"-c", "commit.gpgsign=false",
	}, args...)
	out, err := git(context.Background(), deps.RealRunner{}, full...)
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSpace(string(out))
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for path, content := range files {
		full := filepath.Join(dir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// landedRepo is a repository whose working tree, against the returned base,
// holds one change of every exclusion class: code 9 lines (app.go +2, old.go
// deleted -4, new.go 3 with no final newline, a pure rename 0), tests 18,
// docs 5, generated 8, locks 6, binary 2 files, and an ignored file.
func landedRepo(t *testing.T) (dir, base string) {
	t.Helper()
	dir = testRepo(t)
	writeFiles(t, dir, map[string]string{
		".gitignore": "ignored.go\n", "src/app.go": "package app\n\nfunc A() {}\n",
		"src/old.go": "package app\n\n// old\nfunc Old() {}\n", "src/move_me.go": "package app\n// moved\n",
		"docs/guide.go": "package docs\n", "logo.bin": "PNG\x00\x01\x02", "go.sum": "a v1 h1:x\n",
	})
	runGit(t, dir, "add", "-A")
	runGit(t, dir, "commit", "-q", "-m", "base")
	base = runGit(t, dir, "rev-parse", "HEAD")
	writeFiles(t, dir, map[string]string{"src/app.go": "package app\n\nfunc A() {}\nfunc B() {}\nfunc C() {}\n"})
	runGit(t, dir, "commit", "-q", "-am", "after the base")
	if err := os.Remove(filepath.Join(dir, "src", "old.go")); err != nil {
		t.Fatal(err)
	}
	runGit(t, dir, "mv", "src/move_me.go", "src/moved.go")
	writeFiles(t, dir, map[string]string{
		"src/new.go": "package app\n\nvar n = 1", "ignored.go": strings.Repeat("x\n", 10),
		"src/app_test.go":  "package app\n\nimport \"testing\"\n\nfunc TestA(t *testing.T) {}\n",
		"pkg/test_tool.py": "a\nb\n", "pkg/tool_test.py": "a\nb\n", "web/a.test.js": "a\n", "web/b.spec.ts": "a\n",
		"internal/testdata/x.go": "a\nb\nc\n", "web/__tests__/c.js": "a\n", "lib/fixtures/f.go": "a\n",
		"tests/e2e.go": "a\n", "test/t.go": "a\n",
		"README.md": "# r\n\n", "notes.txt": "n\n", "guide.rst": "g\n", "docs/guide.go": "package docs\n// more\n",
		"templates/generated/g.go": "a\nb\n", "pfm/harness-prompts/generated/c.md": "c\n", "api.pb.go": "a\n",
		"z_gen.go": "a\n", "q.gen.ts": "a\n", "marked.go": "// Code generated by tool. DO NOT EDIT.\npackage x\n",
		"go.sum": "a v1 h1:x\nb v1 h1:y\n", "Cargo.lock": "a\n", "package-lock.json": "{}\n", "pnpm-lock.yaml": "a\n",
		"yarn.lock": "a\n", "npm-shrinkwrap.json": "{}\n",
		"logo.bin": "PNG\x00\x01\x02\x03", "blob.dat": "bin\x00ary\n",
	})
	runGit(t, dir, "add", "src/app_test.go")
	return dir, base
}

// TestMeasureLandedSkipsAnUntrackedFileThatVanished: a build or test temp deleted between
// `git ls-files --others` and its stat is gone, as readHead reads a deleted tracked file, and
// neither fails the measure nor counts as a file.
func TestMeasureLandedSkipsAnUntrackedFileThatVanished(t *testing.T) {
	top := t.TempDir()
	writeFiles(t, top, map[string]string{"kept.go": "package a\n"})
	landed := &landedLines{top: top}
	for _, path := range []string{"gone.go", "kept.go"} {
		if err := landed.addUntracked(path); err != nil {
			t.Fatalf("addUntracked(%s) = %v, want nil", path, err)
		}
	}
	if landed.files != 1 || landed.untrackedFiles != 1 || landed.code != 1 {
		t.Errorf("files %d untracked %d code %d, want only kept.go counted (1, 1, 1)",
			landed.files, landed.untrackedFiles, landed.code)
	}
}
