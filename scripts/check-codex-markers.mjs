#!/usr/bin/env node
// ---------------------------------------------------------------------------
// check-codex-markers.mjs — every build-codex.mjs copy must claim EVERY marker
// generation that writes into $HOME/.codex.
//
// Two compilers have written the same outputs across this repo's history: the
// native `pfm codex build` (this repo's single writer) and the blueprint's
// shipped JS build-codex.mjs (the adopter-side twin). Each refuses to touch a
// file it does not recognize as generated (so it never clobbers hand-written
// work). That guard turns into silent drift the moment one compiler stops
// recognizing the other's marker: every file the other wrote reports STALE
// forever and no run can heal it.
//
// This gate reads each remaining compiler copy's GENERATED_RE literal and runs
// it against a real header of every historical generation, plus a hand-written
// file that must still be rejected. It ALSO reconciles every tracked file
// carrying a generation marker against its declared source — a marked file
// whose source is gone is a fossil, reported by name — and every tracked
// SYMLINK against its target, because a mirror link into untracked territory
// is a promise no clone can keep.
//
// usage: node scripts/check-codex-markers.mjs [file...]   (defaults to the blueprint copy)
// ---------------------------------------------------------------------------
import { existsSync, lstatSync, readFileSync, readlinkSync } from 'node:fs';
import { dirname, isAbsolute, relative, resolve, sep } from 'node:path';

const FILES = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ['templates/project/scripts/build-codex.mjs'];

// Each generation's real first-line header, as written on disk today.
const CLAIMED = {
  'pfm codex build': '# Generated by pfm codex build from $HOME/.claude/commands/chat/inject.md; do not edit',
  // frozen historical marker — pre-rename generated files
  'legacy build-codex.mjs':
    '# Generated by .claude/scripts/build-codex.mjs from .claude/commands/pcm.md; do not edit',
  // frozen historical marker — pre-rename generated files
  'pre-blueprint infra': '# Generated from .professor/infra/codex/prompts/pcm.md; do not edit',
};
const REJECTED = '# A hand-written skill nobody generated. Do not delete me.';

let failed = 0;
const fail = (msg) => {
  console.error(`FAIL ${msg}`);
  failed++;
};

for (const file of FILES) {
  let literal;
  try {
    literal = readFileSync(file, 'utf8').match(/^const GENERATED_RE = \/(.+)\/;$/m)?.[1];
  } catch (e) {
    fail(`${file} — unreadable (${e.code})`);
    continue;
  }
  if (!literal) {
    fail(`${file} — no single-line \`const GENERATED_RE = /.../;\` found`);
    continue;
  }

  const re = new RegExp(literal);
  for (const [generation, header] of Object.entries(CLAIMED)) {
    if (!re.test(header)) fail(`${file} — does not claim "${generation}" output; it would strand as STALE`);
  }
  if (re.test(REJECTED)) fail(`${file} — claims an UNMARKED file; the clobber guard is gone`);
}

// ---------------------------------------------------------------------------
// Orphan reconcile — a marker is a CLAIM ABOUT A SOURCE, and the claim must
// still be true. Every TRACKED file carrying a "Generated by … from <src>;"
// header names the file(s) it was compiled from ("+" separates co-sources);
// if NONE of them exists anymore, the file is a fossil — its project died,
// its commands retired — that every compiler will refuse to touch and no
// run can heal. This check reports all three broken/reconcile states by name:
// ORPHAN (fail), tracked-but-unreadable (fail), and tracked-but-deleted (warn,
// counted). Marker text alone reads as healthy forever, which is how a deleted
// project's instruction file survives in the tree.
// ---------------------------------------------------------------------------
import { execFileSync } from 'node:child_process';

const MARKER_RE = /(?:^|[>\n#])\s*.*Generated by [^;\n]+? from (.+?);\s*(?:do not edit|$)/gm;
const VIRTUAL_GENERATORS = new Set(['pfm opencode build']);
let marked = 0;
let orphans = 0;
const deletedTracked = [];
const notScannable = [];
let tracked = [];
try {
  const gitArgs = [];
  if (process.env.PFM_DEV_REPO_GIT_DIR && process.env.PFM_DEV_REPO_WORK_TREE) {
    gitArgs.push(
      `--git-dir=${process.env.PFM_DEV_REPO_GIT_DIR}`,
      `--work-tree=${process.env.PFM_DEV_REPO_WORK_TREE}`,
      '-c',
      `safe.directory=${process.env.PFM_DEV_REPO_WORK_TREE}`,
    );
  }
  tracked = execFileSync('git', [...gitArgs, 'ls-files', '-z'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    .split('\0')
    .filter(Boolean);
} catch {
  fail('orphan reconcile — git ls-files did not run; the scan below never happened');
}
for (const file of tracked) {
  let content;
  try {
    content = readFileSync(file, 'utf8');
  } catch (e) {
    if (e.code === 'ENOENT') {
      // Tracked but gone from disk: a deletion awaiting its commit. Named,
      // counted, not failed — the commit that records it is the fix.
      deletedTracked.push(file);
      continue;
    }
    if (e.code === 'EISDIR') {
      // A tracked path that is not a regular file — a symlink to a directory,
      // say — carries no marker header to claim and never could. It is outside
      // this gate's domain rather than something it failed to read, so it is
      // NAMED and excluded, never silently skipped: it must not read as scanned.
      // Failing here instead made the verdict depend on whether the link
      // happened to materialize — deleted in one checkout it warned and passed,
      // present in another it failed, on identical content.
      notScannable.push(file);
      continue;
    }
    fail(`${file} — tracked but unreadable (${e.code}); this gate could not look`);
    continue;
  }
  const header = content.slice(0, 600);
  MARKER_RE.lastIndex = 0;
  const match = MARKER_RE.exec(header);
  if (!match) continue;
  marked++;
  const missing = match[1]
    .split(/\s*\+\s*/)
    .map((part) => part.trim().replace(/^\$HOME\//, `${process.env.HOME}/`))
    // A co-source may be OPTIONAL (an absent .mcp.json legitimately removes
    // itself from the inputs); the fossil test is that NO named input exists.
    // Native generators are command identities rather than repository paths;
    // recognize the exact registered writer without treating arbitrary marker
    // prose as a source that exists.
    .filter((part) => !VIRTUAL_GENERATORS.has(part) && !existsSync(part));
  if (missing.length && missing.length === match[1].split(/\s*\+\s*/).length) {
    orphans++;
    fail(`ORPHAN ${file} — none of its declared sources exist (${missing.join(', ')}); delete this fossil`);
  }
}

// ---------------------------------------------------------------------------
// Tracked-symlink reconcile — a tracked symlink promises that its target
// arrives with the clone. Whole mirror trees here are ignored BY DESIGN
// (`.claude/skills/`, `.opencode/skills/` — source-fetched, regenerated by
// `pfm codex build`), so a tracked link into one of them resolves on the
// machine that added it and nowhere else. In a fresh checkout it is simply a
// path that is not there, and it surfaces as whatever the first gate to walk
// the tree happens to say — "unreadable", EISDIR, a dangling-source warning —
// never as the broken promise it is. Both states are named here.
// ---------------------------------------------------------------------------
const trackedSet = new Set(tracked);
let links = 0;
for (const file of tracked) {
  let stat;
  try {
    stat = lstatSync(file);
  } catch (e) {
    // ENOENT is already accounted for above as tracked-but-deleted.
    if (e.code !== 'ENOENT') fail(`${file} — tracked but could not be stat'd (${e.code}); its link state was never determined`);
    continue;
  }
  if (!stat.isSymbolicLink()) continue;
  links++;
  const raw = readlinkSync(file);
  const target = resolve(dirname(file), raw);
  const rel = relative(process.cwd(), target).split(sep).join('/');
  if (!existsSync(target)) {
    fail(`DANGLING-LINK ${file} -> ${raw} — the target does not exist; every clone gets this same broken path`);
  } else if (!rel.startsWith('../') && !isAbsolute(rel) && !trackedSet.has(rel)) {
    fail(
      `UNTRACKED-TARGET ${file} -> ${raw} — the target (${rel}) is inside this repo but is NOT tracked, so only this working copy can resolve the link; untrack the link and let its generator recreate it`,
    );
  }
}

if (deletedTracked.length > 0) {
  console.error(`WARN tracked-but-deleted (awaiting commit): ${deletedTracked.join(', ')}`);
}
if (notScannable.length) {
  console.error(`WARN not-scannable (tracked, not a regular file — carries no marker, examined by nothing): ${notScannable.join(', ')}`);
}
if (failed) {
  console.error(
    `codex marker claim FAILED — ${failed} problem(s); emitted-source reconcile: ${marked} marked file(s), ${orphans} orphan(s); ${links} tracked symlink(s); ${deletedTracked.length} tracked-but-deleted`,
  );
  process.exit(1);
}
console.log(
  `codex marker claim OK — ${FILES.length} compiler copy/copies claim all ${Object.keys(CLAIMED).length} generations, reject unmarked files; ${marked} marked file(s), 0 orphans; ${links} tracked symlink(s) resolve to tracked targets; ${deletedTracked.length} tracked-but-deleted`,
);
