const variantSourceAgent = "---\nname: lead\ndescription: >\n  Folded lead description\n  over two lines.\ntools: Read, Agent\n" +
	"model: opus # tier note\neffort: low\n---\n\nLead body, byte for byte.\n\n## Section\n\n\"quoted\" text.\n"

func variantAgentsDir(home string) string {
	return filepath.Join(home, ".professor", "templates", "global", "agents")
}

func TestGlobalAgentVariantOverridesOnlyTheDeclaredFrontmatter(t *testing.T) {
	home := t.TempDir()
	dir := variantAgentsDir(home)
	writeTestFile(t, filepath.Join(dir, "lead.md"), variantSourceAgent)
	writeTestFile(t, filepath.Join(dir, GlobalAgentVariantsFile),
		`{"super-lead":{"from":"lead","description":"It's the \"deep\" lead: more effort.","effort":"medium"}}`)

	variants, err := LoadGlobalAgentVariants(dir, filepath.Join(home, "out"))
	if err != nil {
		t.Fatalf("LoadGlobalAgentVariants: %v", err)
	}
	if len(variants) != 1 || variants[0].Name != "super-lead" || variants[0].From != "lead" {
		t.Fatalf("variants = %#v, want one super-lead from lead", variants)
	}
	if want := filepath.Join(home, "out", "super-lead.md"); variants[0].Path != want {
		t.Fatalf("path = %s, want %s", variants[0].Path, want)
	}
	want := "---\n# Generated by pfm from templates/global/agents/lead.md + variants.json — edit the source\n" +
		"name: super-lead\ndescription: 'It''s the \"deep\" lead: more effort.'\ntools: Read, Agent\n" +
		"model: opus # tier note\neffort: medium\n---\n\nLead body, byte for byte.\n\n## Section\n\n\"quoted\" text.\n"
	if got := string(variants[0].Content); got != want {
		t.Fatalf("rendered variant:\n%q\nwant:\n%q", got, want)
	}
	fields, _, err := parseFrontmatter(string(variants[0].Content))
	if err != nil {
		t.Fatalf("rendered variant does not parse: %v", err)
	}
	if fields["description"] != `It's the "deep" lead: more effort.` {
		t.Fatalf("description round-trip = %q", fields["description"])
	}
}

// A variant's "replace" rewrites its body: each key is text that occurs exactly
// once in the source body, swapped for its value; the frontmatter and every
// other body byte carry through.
func TestGlobalAgentVariantReplaceRewritesTheBodyOnly(t *testing.T) {
	home := t.TempDir()
	dir := variantAgentsDir(home)
	writeTestFile(t, filepath.Join(dir, "lead.md"), variantSourceAgent)
	writeTestFile(t, filepath.Join(dir, GlobalAgentVariantsFile),
		`{"super-lead":{"from":"lead","effort":"medium","replace":{`+
			`"byte for byte":"at depth","## Section":"## Deep section\nwith two lines"}}}`)

	variants, err := LoadGlobalAgentVariants(dir, filepath.Join(home, "out"))
	if err != nil {
		t.Fatalf("LoadGlobalAgentVariants: %v", err)
	}
	want := "---\n# Generated by pfm from templates/global/agents/lead.md + variants.json — edit the source\n" +
		"name: super-lead\ndescription: >\n  Folded lead description\n  over two lines.\ntools: Read, Agent\n" +
		"model: opus # tier note\neffort: medium\n---\n\nLead body, at depth.\n\n" +
		"## Deep section\nwith two lines\n\n\"quoted\" text.\n"
	if got := string(variants[0].Content); got != want {
		t.Fatalf("rendered variant:\n%q\nwant:\n%q", got, want)
	}
}

