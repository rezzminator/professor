#!/usr/bin/env node
// build-opencode.mjs — compile every OpenCode artifact from the Claude sources of truth.
//
// The OpenCode mirror compiler — sibling of this repo's single Codex
// writer (`pfm codex build`) and of the blueprint's shipped JS build-codex.mjs:
// same discipline, this runtime's shapes.
// Sources (hand-edited, NEVER written by this script):
//   .claude/agents/*.md                  → .opencode/agent/{name}.md
//   <project>/.claude/agents/*.md        → .opencode/agent/{name}-{proj}.md
//   .claude/commands/**/*.md             → .opencode/command/{flat-name}.md
//   .claude/skills/*/                    → .opencode/skills/{name} (dir symlink)
//   $HOME/.claude/commands/**/*.md       → $HOME/.config/opencode/command/
//                                          ($HOME/.claude/skills is auto-loaded by
//                                          OpenCode itself — nothing to compile)
//   .mcp.json                            → the managed `mcp` object inside
//                                          .opencode/opencode.jsonc
//   LICENSE, SECURITY.md                 → .opencode/{LICENSE,SECURITY.md} (byte copies)
//
// .opencode/opencode.jsonc — the script owns exactly three keys: `$schema`,
// `permission` (repo law pinned at the harness layer: guarded-file edit denies,
// non-gitter Git-write denies), and `mcp`. Any OTHER key present in a
// marked file survives regeneration untouched (an adopter's `model` or
// `plugin` entry must not vanish under the compiler); keys in an UNMARKED file
// are a CONFLICT — reported, never touched.
//
// Modes:  generate (default) — write outputs, delete orphans, idempotent
//         check              — report MISSING/STALE/ORPHAN/CONFLICT, write nothing, exit 1 on any
//         doctor             — check, plus every emitted file must PARSE: opencode.jsonc
//                              strips its comment header and JSON.parses; each agent and
//                              command must carry valid frontmatter with a non-empty
//                              description. Currency is not validity.
//
// Transforms are pure string operations:
//   verbatim copy + nested command names flattened to the flat form
//     OpenCode's loader requires (/wave:orchestrator → /wave-orchestrator;
//     already-flat names pass through untouched). No model-alias swap: § Model
//     Selection tier words bind every harness; no OpenCode model roster is
//     pinned anywhere (agent files omit `model` and inherit the session model).
// Every generated file carries a marker line; the script only ever overwrites or
// deletes marker-carrying files (or symlinks into .claude trees). Anything else at
// a managed path is a CONFLICT — reported, never touched.

import {
  existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, readlinkSync,
  rmSync, symlinkSync, writeFileSync, statSync, realpathSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
// Tests and repo-only regeneration can redirect the global-output surface away
// from the live OpenCode store while preserving the normal installer-facing default.
const HOME = process.env.OPENCODE_BUILD_HOME ?? process.env.HOME;
const GLOBAL_DIR = join(HOME, '.config/opencode');
const MODE = process.argv[2] ?? 'generate';
if (!['generate', 'check', 'doctor'].includes(MODE)) {
  console.error(`usage: build-opencode.mjs [generate|check|doctor]`);
  process.exit(2);
}

const SELF = '.claude/scripts/build-opencode.mjs';
const marker = (src) => `Generated by ${SELF} from ${src}; do not edit — edit the source, then re-run: node ${SELF}`;
const GENERATED_RE = /Generated by \.claude\/scripts\/build-opencode\.mjs/;

const agentPreamble = (name) => `You are the ${name} role in the Professor repo, running as a native OpenCode subagent.
First action: read the repo root AGENTS.md in full — its laws bind you (only gitter may write Git; guarded files are read-only for every subagent) and its § OpenCode adapter maps any Claude-harness mechanic named below. Then execute the protocol below exactly; your mode/task comes from the dispatch prompt.
Stamp every deliverable, report, or verdict you produce with: Executor: opencode-subagent/${name}

`;

// ---------- helpers ----------------------------------------------------------

const read = (p) => readFileSync(p, 'utf8');
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();

function* walkMd(dir, ancestors = new Set()) {
  const physical = realpathSync(dir);
  if (ancestors.has(physical)) throw new Error(`command source symlink cycle at ${dir}`);
  const visiting = new Set([...ancestors, physical]);
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = join(dir, e.name);
    if (isDir(p)) yield* walkMd(p, visiting);
    else if (e.name === 'SKILL.md') yield { dir: dirname(p), skillDir: true };
    else if (e.name.endsWith('.md') && e.name !== 'README.md') yield { file: p };
  }
}

// Frontmatter: raw lines between the first two `---` fences + naive key: value map.
// Same block-scalar handling as build-codex.mjs (folded > joins with spaces,
// literal | joins with newlines) — the two compilers parse identically or one
// of them is wrong.
function parseFm(text) {
  const lines = text.split('\n');
  if (lines[0] !== '---') return { fm: null, body: text, fields: {} };
  const end = lines.indexOf('---', 1);
  if (end === -1) return { fm: null, body: text, fields: {} };
  const fm = lines.slice(1, end);
  const fields = {};
  for (let i = 0; i < fm.length; i++) {
    const block = fm[i].match(/^([A-Za-z-]+):\s*([>|])[-+]?\s*$/);
    if (block) {
      const [, key, style] = block;
      const chunk = [];
      let indent = null;
      while (i + 1 < fm.length) {
        const next = fm[i + 1];
        if (next.trim() === '') { chunk.push(''); i++; continue; }
        const m = next.match(/^(\s+)/);
        if (!m || (indent !== null && m[1].length < indent)) break;
        indent ??= m[1].length;
        chunk.push(next.slice(indent));
        i++;
      }
      while (chunk.length && chunk[chunk.length - 1] === '') chunk.pop();
      fields[key] = chunk.join(style === '>' ? ' ' : '\n');
      continue;
    }
    const m = fm[i].match(/^([A-Za-z-]+):\s*(.*)$/);
    if (m) fields[m[1]] = m[2];
  }
  return { fm, body: lines.slice(end + 1).join('\n'), fields };
}

const flatName = (rel) => rel.replace(/\.md$/, '').split('/').join('-');
const colonName = (rel) => rel.replace(/\.md$/, '').split('/').join(':');

// Command-prefix roster — Claude invokes `.claude/commands/**` as `/name`
// (nested dirs join with `:`); OpenCode invokes the compiled command as
// `/flat-name` (its loader scans `**/*.md` and names commands by filename, so
// nesting cannot survive). Only colon-forms rewrite; a flat name is already
// valid OpenCode syntax and passes through byte-identical. The roster is the
// exact set of names backed by a real .md file on disk — never a hand-written
// list, never a generic rewrite (that would corrupt path fragments like
// /scripts, /src). A directory alone (wave/, no wave.md) contributes no entry.
const commandRoster = new Map(); // "a:b" colon-form -> "/flat-form" (only where they differ)
// Include shipped globals so repository output is stable in a clean HOME.
for (const commandsRoot of [join(ROOT, '.claude/commands'), join(ROOT, 'templates/global/commands'), join(HOME, '.claude/commands')]) {
  if (!isDir(commandsRoot)) continue;
  for (const entry of walkMd(commandsRoot)) {
    const rel = relative(commandsRoot, entry.skillDir ? entry.dir : entry.file);
    const colon = colonName(rel);
    const flat = flatName(rel);
    if (colon !== flat) commandRoster.set(colon, `/${flat}`);
  }
}
const CMD_RE = commandRoster.size
  ? new RegExp(`(?<![\\w/.-])/(${[...commandRoster.keys()].sort((a, b) => b.length - a).join('|')})(?![\\w:-])`, 'g')
  : null;
const cmdSwap = (s) => (CMD_RE ? s.replace(CMD_RE, (_, name) => commandRoster.get(name)) : s);

const yamlQuote = (s) => JSON.stringify(String(s));

// ---------- compile ----------------------------------------------------------
// outputs: absolute path → { content } | { link: target }
const outputs = new Map();
const notes = [];
// Source links whose target is gone. Collected during compile, reported below:
// a source that cannot be READ is a named gap, never a silently missing output.
const danglingSources = [];

// Projects = top-level dirs carrying a CLAUDE.md (dynamic; .worktrees etc. have none).
// templates/ is excluded: its CLAUDE.md is the adopter TEMPLATE (placeholder text),
// not this repo's instructions — mirroring it mints placeholder agents.
const projects = readdirSync(ROOT, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name !== 'templates' && existsSync(join(ROOT, e.name, 'CLAUDE.md')))
  .map((e) => e.name)
  .sort();

// 1) Agents → .opencode/agent/{name}.md. Root name wins a collision — it is the
//    registered wrapper; the child protocol it points at still loads at runtime.
// Every source role is registered. The global Git-write deny remains in force
// for all roles except gitter's explicit per-agent override below.
const agentSources = [];
const rootAgentsDir = join(ROOT, '.claude/agents');
if (isDir(rootAgentsDir)) {
  for (const f of readdirSync(rootAgentsDir).filter((n) => n.endsWith('.md')).sort()) {
    const name = f.replace(/\.md$/, '');
    agentSources.push({ src: join(rootAgentsDir, f), name });
  }
}
for (const p of projects) {
  const d = join(ROOT, p, '.claude/agents');
  if (!isDir(d)) continue;
  const suffix = p;
  for (const f of readdirSync(d).filter((n) => n.endsWith('.md')).sort()) {
    const base = f.replace(/\.md$/, '');
    const name = `${base}-${suffix}`;
    if (agentSources.some((a) => a.name === name)) {
      notes.push(`skip ${p}/.claude/agents/${f} — root agent ${name} owns the registration`);
      continue;
    }
    agentSources.push({ src: join(d, f), name });
  }
}
for (const { src, name } of agentSources) {
  const srcRel = relative(ROOT, src);
  const { body, fields } = parseFm(read(src));
  // No `model` frontmatter on purpose: no host model roster is pinned for
  // OpenCode (a fabricated provider/model id fails at spawn and reads as a
  // harness bug). The tier travels as prose; the session model serves it.
  const tier = fields.model ? `Model tier: ${fields.model} per the fleet prompt § Model Selection — run this host's matching model.\n\n` : '';
  const permission = name === 'gitter' ? 'permission:\n  bash:\n    "git *": allow\n' : '';
  outputs.set(join(ROOT, '.opencode/agent', `${name}.md`), {
    content:
      `---\n# ${marker(srcRel)}\ndescription: ${yamlQuote(cmdSwap(fields.description ?? ''))}\nmode: subagent\n${permission}---\n` +
      `${agentPreamble(name)}${tier}${cmdSwap(body.trim())}\n`,
  });
}

// 2) Commands → .opencode/command/{flat-name}.md. Frontmatter carries only what
//    OpenCode's command schema accepts (description); Claude-harness fields
//    (allowed-tools, argument-hint, disable-model-invocation) are dropped — a
//    side-effect command stays user-invoked here because commands are slash-only.
function compileCommands(srcRoot, srcLabel, emit) {
  if (!isDir(srcRoot)) return;
  for (const entry of walkMd(srcRoot)) {
    const file = entry.skillDir ? join(entry.dir, "SKILL.md") : entry.file;
    const rel = relative(srcRoot, entry.skillDir ? entry.dir : file);
    if (!existsSync(file)) {
      // A command link pointing at a deleted blueprint file (a retired global
      // command). readFileSync would throw ENOENT and abort the whole compile,
      // so ONE stale link takes every other command's output down with it —
      // and the failure reads as a crash, not as the one missing source it is.
      danglingSources.push(`${srcLabel}/${rel}`);
      continue;
    }
    const flat = flatName(rel);
    const { body, fields } = parseFm(read(file));
    emit({
      flat,
      content: `---\n# ${marker(`${srcLabel}/${rel}`)}\ndescription: ${yamlQuote(cmdSwap(fields.description ?? ''))}\n---\n${cmdSwap(body)}`,
    });
  }
}

compileCommands(join(ROOT, '.claude/commands'), '.claude/commands', (o) => {
  outputs.set(join(ROOT, '.opencode/command', `${o.flat}.md`), { content: o.content });
});

// Global: $HOME/.claude/commands → $HOME/.config/opencode/command/. Skills need
// no global compile — OpenCode auto-loads $HOME/.claude/skills itself.
compileCommands(join(HOME, '.claude/commands'), '$HOME/.claude/commands', (o) => {
  outputs.set(join(GLOBAL_DIR, 'command', `${o.flat}.md`), { content: o.content });
});

// Repo skill dirs → true symlinks (a symlinked skill DIRECTORY loads; keep zero
// generated bytes).
const skillsDir = join(ROOT, '.claude/skills');
if (isDir(skillsDir)) {
  for (const s of readdirSync(skillsDir).sort()) {
    if (!isDir(join(skillsDir, s))) continue;
    const dst = join(ROOT, '.opencode/skills', s);
    outputs.set(dst, { link: relative(dirname(dst), join(skillsDir, s)) });
  }
}

// 3) .opencode/opencode.jsonc — owned keys: $schema, permission, mcp; every other
//    key found in a marked file survives. Deterministic serialization: sorted
//    extra keys, fixed order otherwise, so generate is stable across runs.
const PERMISSION_POLICY = {
  // LAST matching rule wins (insertion order matters): broad allow first, the
  // narrow denies after. OpenCode keeps the guarded-file and publication pins
  // at its harness layer; the active main Codex fallback does not apply here.
  // Every permission OpenCode ships defaults to allow except `external_directory`
  // and `doom_loop`, which default to ask — an unattended chat then stalls on
  // the first read outside the worktree (an audit under the live checkout's
  // tmp/, the host pfm binary). Pin both to allow; the denies below still win.
  '*': 'allow',
  external_directory: 'allow',
  doom_loop: 'allow',
  edit: {
    '**': 'allow',
    '**/.claude/**': 'deny',
    'AGENTS.md': 'deny',
    '**/AGENTS.md': 'deny',
    'CLAUDE.md': 'deny',
    '**/CLAUDE.md': 'deny',
    '.opencode/**': 'deny',
  },
  bash: {
    '*': 'allow',
    'git commit*': 'deny',
    'git push*': 'deny',
    'git tag*': 'deny',
    'gh release*': 'deny',
  },
};

const CONFIG_HEADER = `// ${marker('.claude/scripts/build-opencode.mjs + .mcp.json')}\n// Sources: this compiler (which owns $schema, permission — repo law pinned at\n// the harness layer) plus the optional .mcp.json (absent when the repo ships\n// no MCP servers; the pin survives without it). Every other key below survives\n// regeneration. Hand edits to the owned keys are overwritten — that is the pin.\n`;

function parseJsonc(text) {
  // Strip whole-line // comments (the only kind the compiler writes) outside of
  // string literals, then parse as JSON.
  let out = '';
  let inStr = false, esc = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inStr) {
      out += c;
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++;
      continue;
    }
    out += c;
  }
  return JSON.parse(out);
}

function serializeConfig(extra, mcpProblems) {
  const cfg = { $schema: 'https://opencode.ai/config.json', ...extra, permission: PERMISSION_POLICY };
  if (mcpProblems.exists && Object.keys(mcpProblems.mcp).length) cfg.mcp = mcpProblems.mcp;
  return `${CONFIG_HEADER}${JSON.stringify(cfg, null, 2)}\n`;
}

{
  const cfgPath = join(ROOT, '.opencode/opencode.jsonc');
  const mcpPath = join(ROOT, '.mcp.json');
  const OWNED = new Set(['$schema', 'permission', 'mcp']);
  let extra = {};
  const currentRaw = existsSync(cfgPath) && !isLink(cfgPath) ? read(cfgPath) : null;
  if (currentRaw !== null) {
    try {
      const parsed = parseJsonc(currentRaw);
      if (!GENERATED_RE.test(currentRaw.slice(0, 600))) {
        notes.push(`CONFLICT-SHAPE ${cfgPath} — exists without this compiler's marker; refusing to derive extra keys from it`);
      } else {
        for (const [k, v] of Object.entries(parsed)) if (!OWNED.has(k)) extra[k] = v;
      }
    } catch (e) {
      notes.push(`unparseable ${cfgPath} (${e.message}) — regenerating from sources; adopter keys could not be preserved`);
    }
  }
  let mcp = {};
  let hasMcp = false;
  if (existsSync(mcpPath)) {
    hasMcp = true;
    const servers = JSON.parse(read(mcpPath)).mcpServers ?? {};
    for (const name of Object.keys(servers).sort()) {
      const s = servers[name];
      if (s.command) {
        mcp[name] = {
          type: 'local',
          command: [s.command, ...(Array.isArray(s.args) ? s.args : [])],
          enabled: true,
          ...(s.env && Object.keys(s.env).length ? { environment: s.env } : {}),
        };
      } else if (s.url) {
        mcp[name] = { type: 'remote', url: s.url, enabled: true, ...(s.headers ? { headers: s.headers } : {}) };
      } else {
        notes.push(`mcp ${name}: neither command nor url — skipped, never silently dropped from the config`);
        continue;
      }
      const unmapped = Object.keys(s).filter((k) => !['command', 'args', 'env', 'url', 'type', 'headers'].includes(k));
      if (unmapped.length) notes.push(`mcp ${name}: fields not mapped to opencode config: ${unmapped.join(', ')}`);
    }
  }
  outputs.set(cfgPath, { content: serializeConfig(extra, { exists: hasMcp, mcp }) });
}

// 4) .opencode/{LICENSE,SECURITY.md} — byte copies of the root files. Plugin
// scanners score .opencode/ as a package of its own and read LICENSE without
// following symlinks, so only a real copy counts. A copy carries no marker;
// these two paths are claimable by name instead (see claimable). A missing
// root source is a note, not a silent skip.
const MIRROR_COPIES = new Set(['LICENSE', 'SECURITY.md'].map((f) => join(ROOT, '.opencode', f)));
for (const f of ['LICENSE', 'SECURITY.md']) {
  const src = join(ROOT, f);
  if (!existsSync(src)) { notes.push(`missing ${src} — nothing to mirror into .opencode/${f}`); continue; }
  outputs.set(join(ROOT, '.opencode', f), { content: read(src) });
}

// ---------- reconcile --------------------------------------------------------

function isLink(p) {
  try { return lstatSync(p).isSymbolicLink(); } catch { return false; }
}
const claimable = (p) => {
  if (isLink(p)) return true;
  if (MIRROR_COPIES.has(p)) return true;
  if (!existsSync(p)) return true;
  const st = lstatSync(p);
  if (st.isFile()) return GENERATED_RE.test(read(p).slice(0, 600));
  if (st.isDirectory()) {
    const sk = join(p, 'SKILL.md');
    return existsSync(sk) && GENERATED_RE.test(read(sk).slice(0, 600));
  }
  return false;
};

const problems = [];

// A dangling source is a coverage gap either way, and it is always stated.
// `generate` states it and keeps going, so one stale link cannot cost every
// other command its output; `check`/`doctor` refuse, because the mirror is not
// current while a source it should have compiled is unreadable.
for (const src of danglingSources) {
  const line = `DANGLING ${src} — source link target is gone; nothing compiled from it (\`pfm install\` prunes an orphaned global-command link)`;
  if (MODE === 'generate') notes.push(line);
  else problems.push(line);
}
let wrote = 0, unchanged = 0, deleted = 0;

for (const [dst, out] of [...outputs.entries()].sort()) {
  if (out.link) {
    if (isLink(dst) && readlinkSync(dst) === out.link) { unchanged++; continue; }
    if (MODE === 'check') { problems.push(`${isLink(dst) || existsSync(dst) ? 'STALE ' : 'MISSING'} ${dst} (want symlink → ${out.link})`); continue; }
    if (!claimable(dst)) { problems.push(`CONFLICT ${dst} — exists without a generated marker; not touching it`); continue; }
    rmSync(dst, { recursive: true, force: true });
    mkdirSync(dirname(dst), { recursive: true });
    symlinkSync(out.link, dst);
    wrote++;
  } else {
    const current = existsSync(dst) && !isLink(dst) && lstatSync(dst).isFile() ? read(dst) : null;
    if (current === out.content) { unchanged++; continue; }
    if (MODE === 'check') { problems.push(`${current === null ? 'MISSING' : 'STALE '} ${dst}`); continue; }
    if (!claimable(dst)) { problems.push(`CONFLICT ${dst} — exists without a generated marker; not touching it`); continue; }
    if (isLink(dst)) rmSync(dst);
    mkdirSync(dirname(dst), { recursive: true });
    writeFileSync(dst, out.content);
    wrote++;
  }
}

// Doctor: currency validated above is not validity. Every emitted artifact must
// PARSE — a config that fails OpenCode's loader or an agent whose frontmatter
// the loader rejects is broken at startup, not at git-diff time.
if (MODE === 'check' || MODE === 'doctor') {
  const cfgPath = join(ROOT, '.opencode/opencode.jsonc');
  if (existsSync(cfgPath)) {
    try { parseJsonc(read(cfgPath)); } catch (e) { problems.push(`INVALID ${cfgPath} — does not parse (${e.message})`); }
  }
  for (const d of [join(ROOT, '.opencode/agent'), join(ROOT, '.opencode/command'), join(GLOBAL_DIR, 'command')]) {
    if (!isDir(d)) continue;
    for (const f of readdirSync(d).filter((n) => n.endsWith('.md')).sort()) {
      const p = join(d, f);
      const { fields } = parseFm(read(p));
      if (!fields.description || !fields.description.trim().replaceAll('"', '')) {
        problems.push(`INVALID ${p} — empty description; OpenCode filters it out and the role/command goes silent`);
      }
      if (d.endsWith('/agent') && fields.mode !== 'subagent') {
        problems.push(`INVALID ${p} — mode "${fields.mode}" is not subagent; the compiler only emits subagent roles`);
      }
    }
  }
}

// Orphans: managed dirs may only hold computed outputs. A marker-carrying file/dir
// or a symlink into a .claude tree is ours to delete; anything else is left, loudly.
const managedDirs = [
  join(ROOT, '.opencode/agent'), join(ROOT, '.opencode/command'), join(ROOT, '.opencode/skills'),
  join(GLOBAL_DIR, 'command'),
];
const wanted = new Set(outputs.keys());
for (const d of managedDirs) {
  if (!isDir(d)) continue;
  for (const e of readdirSync(d).sort()) {
    const p = join(d, e);
    if (wanted.has(p)) continue;
    const ours = isLink(p) ? readlinkSync(p).includes('.claude/') : claimable(p) && existsSync(p);
    if (!ours) { notes.push(`unmanaged ${p} — no generated marker, leaving it alone`); continue; }
    if (MODE !== 'generate') { problems.push(`ORPHAN ${p} — no source compiles here anymore`); continue; }
    rmSync(p, { recursive: true, force: true });
    deleted++;
  }
}

// ---------- report -----------------------------------------------------------

for (const n of notes) console.log(`note: ${n}`);
const counts = `${outputs.size} outputs (${agentSources.length} agents, repo+global commands, skill symlinks, opencode.jsonc, LICENSE+SECURITY.md copies) — coverage: repo commands+skills+agents, $HOME commands, repo .mcp.json; NOT covered: hooks (Claude-harness-only), $HOME-level MCP registries, $HOME skills (OpenCode auto-loads them)`;
if (problems.length) {
  for (const p of problems) console.error(p);
  console.error(`${MODE === 'generate' ? 'GENERATE INCOMPLETE' : MODE.toUpperCase() + ' FAIL'} — ${problems.length} problem(s); ${counts}`);
  process.exit(1);
}
console.log(MODE === 'generate'
  ? `generated — ${wrote} written, ${unchanged} unchanged, ${deleted} orphans removed; ${counts}`
  : `${MODE.toUpperCase()} PASS — ${counts}; ${unchanged} verified current`);
