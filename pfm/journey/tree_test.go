//go:build journey

package journey

import "github.com/rezzminator/professor/pfm/journey/harness"

// tree is the owner's day: install; then the day, every branch side by side, each in sessions, panes,
// projects and chat names of its own: a plain terminal typing pfm; an adopter project through pfm init,
// its settling and upstream moves; a Herdr mesh of chats calling each other, across tmux and to an ended
// and a dead chat; a Herdr Claude chat typed, renamed, reloaded, its pane lost, killed and unkilled; the
// default Herdr session's Claude chat from the picker through a turn, reloads, a clear, its end and its
// resume; a question and a sub-agent; Codex and OpenCode chats in Herdr; a Claude and a Codex chat in
// plain terminals; the guards on a project's chat. Each branch ends its chats and its Herdr session when
// its subtree ends. Then the whole machine judged at the join (fleet); a restart chain on two tabs: tmux
// stopped, Herdr stopped and back, a call after the restore and pfm restart; install again, doctor, and
// the uninstall.
func tree() harness.Node[State] {
	return harness.Do("install", install,
		harness.Together("day", nil,
			harness.Do("plain-pfm", plainPfm),
			harness.Do("adopter", nil,
				harness.Do("init", adopterInit,
					harness.Do("adopt", adopt,
						harness.Do("upstream-moves", upstreamMoves,
							harness.Do("project-updates", projectUpdates,
								harness.Do("pin", pinUpdated,
									harness.Do("retired-name", retiredName),
								),
							),
						),
					),
				),
			),
			harness.Do("herdr-mesh", herdrMesh,
				harness.Do("chat-new", chatNew,
					harness.Do("child-new", childNew,
						harness.Do("call", call,
							harness.Do("call-across", callAcross,
								harness.Do("call-dead", callDead),
							),
						),
					),
				),
			),
			harness.Do("herdr-native", herdrSession,
				harness.Do("claude-typed", claudeTyped,
					harness.Do("rename", rename,
						harness.Do("reload-cli", reloadCLI,
							harness.Do("pane-lost", paneLost,
								harness.Do("kill-from-picker", killFromPicker,
									harness.Do("unkill", unkill),
								),
							),
						),
					),
				),
			),
			harness.Do("herdr", herdr,
				harness.Do("claude-from-picker", claudeFromPicker,
					harness.Do("turn", herdrTurn,
						harness.Do("reload-typed", reloadTypedDrawn,
							harness.Do("clear", clearChat,
								harness.Do("reload-again", reloadAgain,
									harness.Do("end", end,
										harness.Do("resume-from-picker", resumeFromPicker),
									),
								),
							),
						),
					),
				),
			),
			harness.Do("herdr-attention", herdrSession,
				harness.Do("claude-from-picker", claudeFromPicker,
					harness.Do("question", question,
						harness.Do("sub-agent", subAgent),
					),
				),
			),
			harness.Do("herdr-codex", herdrSession,
				harness.Do("codex-from-picker", codexFromPicker,
					harness.Do("turn", turn,
						harness.Do("codex-reload", codexReload,
							harness.Do("codex-end", end,
								harness.Do("codex-resume", codexResume,
									harness.Do("resumed-end", end,
										harness.Do("codex-named", codexNamed),
									),
								),
							),
						),
					),
				),
			),
			harness.Do("herdr-opencode", herdrSession,
				harness.Do("opencode-new", opencodeNew,
					harness.Do("opencode-end", opencodeEnd),
				),
			),
			harness.Do("plain-claude", plainClaude,
				harness.Do("turn", turn,
					harness.Do("reload-typed", plainReloadTyped,
						harness.Do("end", plainEnd,
							harness.Do("resume-from-cli", plainResumeFromCLI),
						),
					),
				),
			),
			harness.Do("plain-codex", plainCodex,
				harness.Do("end", plainCodexEnd),
			),
			harness.Do("guards", herdrSession,
				harness.Do("project", guardsProject,
					harness.Do("claude-from-picker", claudeFromPicker,
						harness.Do("git-write-refused", gitWriteRefused),
						harness.Do("git-read-passes", gitReadPasses),
						harness.Do("framework-write-refused", frameworkWriteRefused),
						harness.Do("ordinary-write-passes", ordinaryWritePasses),
						harness.Do("prose-write-passes", proseWritePasses),
					),
				),
			),
		),
		harness.Do("fleet", fleet),
		harness.Do("restart", herdrSession,
			harness.Do("two-tabs", twoTabs,
				harness.Do("tmux-stopped", tmuxStopped),
				harness.Do("herdr-stops", herdrStops,
					harness.Do("herdr-returns", herdrReturns,
						harness.Do("call-after-restore", callAfterRestore,
							harness.Do("pfm-restart", pfmRestart),
						),
					),
				),
			),
		),
		harness.Do("install-again", installAgain),
		harness.Do("doctor", doctor),
		harness.Do("uninstall", uninstall),
	)
}
